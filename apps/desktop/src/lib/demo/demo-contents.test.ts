import { readFileSync } from 'node:fs'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { demoContents } from './demo-contents.js'
import { demoEntries } from './demo-tree.js'

/**
 * The disk file behind a Vite asset URL: `/@fs/<abs>` outside the app root, `/<rel>` inside it, minus any query Vite
 * keeps on it (the sample PDF's `?no-inline`).
 */
function diskPathOf(url: string): string {
  const bare = url.split('?')[0]
  return bare.startsWith('/@fs/') ? bare.slice('/@fs'.length) : path.resolve(process.cwd(), `.${bare}`)
}

/** A `fetch` that serves the real asset bytes from disk, counting requests per URL. */
function diskFetch(requests: Map<string, number>, answer?: (url: string) => Response | undefined) {
  // `demoContents` fetches by the string URL Vite hands it.
  return vi.fn((url: string) => {
    requests.set(url, (requests.get(url) ?? 0) + 1)
    const override = answer?.(url)
    if (override) return Promise.resolve(override)
    return Promise.resolve(new Response(readFileSync(diskPathOf(url))))
  })
}

const extensionOf = (p: string) => p.slice(p.lastIndexOf('.') + 1).toLowerCase()
/** Whether an asset URL is the sample PDF's, whatever query Vite keeps on it. */
const isPdfUrl = (url: string) => extensionOf(url.split('?')[0]) === 'pdf'
const nameOf = (p: string) => p.slice(p.lastIndexOf('/') + 1)

/** The tree's files the viewer shows as text: the text extensions plus the home folder's dotfiles. */
const TEXT_EXTENSIONS = new Set(['md', 'txt', 'html', 'css', 'toml', 'rs'])
const isTextFile = (p: string) => TEXT_EXTENSIONS.has(extensionOf(p)) || nameOf(p).startsWith('.')

const files = demoEntries.filter((e) => e.kind === 'file').map((e) => e.path)

const isPdf = (bytes: Uint8Array) => new TextDecoder().decode(bytes.subarray(0, 5)) === '%PDF-'
const isWebp = (bytes: Uint8Array) => {
  const ascii = new TextDecoder().decode(bytes.subarray(0, 12))
  return ascii.startsWith('RIFF') && ascii.endsWith('WEBP')
}

describe('demoContents', () => {
  let requests: Map<string, number>

  beforeEach(() => {
    requests = new Map()
    vi.stubGlobal('fetch', diskFetch(requests))
  })

  afterEach(() => {
    vi.unstubAllGlobals()
  })

  // The engine takes these bytes by path: one for a path the tree lacks is dead weight the viewer never reaches.
  it('only holds bytes for files the tree lists', async () => {
    const contents = await demoContents()
    const fileSet = new Set(files)
    expect(Object.keys(contents).filter((p) => !fileSet.has(p))).toEqual([])
  })

  it('gives every text, PDF, and picture file in the tree real bytes', async () => {
    const contents = await demoContents()
    const viewable = files.filter((p) => isTextFile(p) || ['pdf', 'png', 'jpg'].includes(extensionOf(p)))
    expect(viewable.length).toBeGreaterThan(20)
    expect(viewable.filter((p) => !(p in contents))).toEqual([])
    expect(viewable.filter((p) => contents[p].byteLength === 0)).toEqual([])
  })

  // The viewer decodes these as UTF-8; a stray byte would show replacement characters on the landing page.
  it('spells every text file as valid UTF-8, ending in a newline', async () => {
    const contents = await demoContents()
    const strict = new TextDecoder('utf-8', { fatal: true })
    const texts = files.filter(isTextFile)
    for (const p of texts) {
      const text = strict.decode(contents[p])
      expect(text.endsWith('\n'), p).toBe(true)
    }
    // The non-Latin file is there for Brief widths and the viewer: its bytes must stay multibyte, not mangled.
    const japanese = strict.decode(contents['/Users/you/Documents/旅行の計画.txt'])
    expect(japanese).toContain('京都')
  })

  it('gives every PDF a real PDF, and every picture a real image', async () => {
    const contents = await demoContents()
    const pdfs = files.filter((p) => extensionOf(p) === 'pdf')
    const pictures = files.filter((p) => ['png', 'jpg'].includes(extensionOf(p)))
    expect(pdfs.filter((p) => !isPdf(contents[p]))).toEqual([])
    // The pictures are the repo's WebP screenshots under the tree's names; the viewer sniffs the bytes.
    expect(pictures.filter((p) => !isWebp(contents[p]))).toEqual([])
  })

  it('fetches each asset once, however many files share it', async () => {
    const contents = await demoContents()
    expect([...requests.values()].every((count) => count === 1)).toBe(true)
    const pdfs = files.filter((p) => extensionOf(p) === 'pdf')
    expect(pdfs.length).toBeGreaterThan(1)
    // Shared, not copied: the nine PDFs are one buffer.
    expect(new Set(pdfs.map((p) => contents[p])).size).toBe(1)
  })

  // A picture that doesn't arrive must not break the boot: its file falls back to the engine's generated bytes.
  it('leaves out an asset whose fetch rejects, keeping the rest', async () => {
    vi.stubGlobal(
      'fetch',
      diskFetch(requests, (url) => {
        if (isPdfUrl(url)) throw new TypeError('offline')
        return undefined
      }),
    )
    const contents = await demoContents()
    expect(files.filter((p) => extensionOf(p) === 'pdf' && p in contents)).toEqual([])
    expect(contents['/Users/you/notes.md']).toBeDefined()
    expect(isWebp(contents['/Users/you/Pictures/Wallpapers/aurora.jpg'])).toBe(true)
  })

  // A 404 page is HTML: handed over as the picture's bytes, the viewer would show a broken image.
  it('leaves out an asset the server answers with an error status', async () => {
    vi.stubGlobal(
      'fetch',
      diskFetch(requests, (url) => (isPdfUrl(url) ? new Response('<h1>Not found</h1>', { status: 404 }) : undefined)),
    )
    const contents = await demoContents()
    expect(files.filter((p) => extensionOf(p) === 'pdf' && p in contents)).toEqual([])
    expect(isWebp(contents['/Users/you/Pictures/Wallpapers/forest.jpg'])).toBe(true)
  })
})
