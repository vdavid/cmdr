/**
 * The default keymap a user gets on each OS, pinned as one reviewed file per platform in
 * `__snapshots__/default-keymap.{macos,windows,linux}.txt`. Any change to a default key shows up
 * as a line diff there, per platform, so "macOS didn't move" and "exactly these keys moved" are
 * provable from the diff.
 *
 * Each line is `<command id>\t<combo>, <combo>` in registry order. A command with no key is
 * listed with an empty list; a command the OS can't offer (`needsCapability` off under that OS's
 * `withCapabilitiesPossibleOn` fixture) is left out. It reads through the public
 * `getDefaultShortcuts`, so the registry's internals can change under it.
 */
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import type { Platform } from '#lib/platform/index.js'
import { withCapabilitiesPossibleOn, withPlatform } from '#lib/platform/test-platform.js'
import { commandOffered, commands } from '#lib/commands/command-registry.js'
import { getDefaultShortcuts, menuCommands } from '#lib/shortcuts/shortcuts-store.js'
import { nativeTextKeys } from '../../routes/(main)/native-text-keys'
import { PLATFORMS } from './platform-shortcuts'
import type { CommandScope } from './types'

describe.each(PLATFORMS satisfies readonly Platform[])('default keymap on %s', (platform) => {
  const undos: (() => void)[] = []

  beforeAll(() => {
    undos.push(withPlatform(platform), withCapabilitiesPossibleOn(platform))
  })

  afterAll(() => {
    for (const undo of undos.reverse()) undo()
  })

  it('matches the pinned keymap', async () => {
    const lines = commands
      .filter(commandOffered)
      .map((command) => `${command.id}\t${getDefaultShortcuts(command.id).join(', ')}`)
    await expect(`${lines.join('\n')}\n`).toMatchFileSnapshot(`./__snapshots__/default-keymap.${platform}.txt`)
  })
})

/**
 * The registry side of the menu bar's parity test: every command with a menu row
 * (`menuCommands`), the first default key a user gets on each OS, written where `cmdr-menu` reads
 * it (`include_str!` in `bar_parity_test.rs`). The Rust test then requires each bar row's
 * accelerator to be what a rebind to that key would register. A stale file fails here, so the
 * bar can't drift from the registry unseen.
 */
describe('the default keys the menu bar mirrors', () => {
  it('match crates/cmdr-menu/src/registry_default_keys.tsv', async () => {
    const lines = [
      '# platform\tcommand id\tfirst default key. Generated by `apps/desktop/src/lib/commands/default-keymap.test.ts`; update with `vitest -u`, ❌ never by hand.',
    ]
    for (const platform of PLATFORMS) {
      const undoPlatform = withPlatform(platform)
      const undoCapabilities = withCapabilitiesPossibleOn(platform)
      try {
        // Keyed by the plain string `menuCommands` holds, so the lookup hands back a typed id.
        const offered = new Map(commands.filter(commandOffered).map((command) => [command.id as string, command.id]))
        for (const id of menuCommands.flatMap((commandId) => offered.get(commandId) ?? [])) {
          lines.push(`${platform}\t${id}\t${getDefaultShortcuts(id)[0] ?? ''}`)
        }
      } finally {
        undoCapabilities()
        undoPlatform()
      }
    }
    await expect(`${lines.join('\n')}\n`).toMatchFileSnapshot(
      '../../../../../crates/cmdr-menu/src/registry_default_keys.tsv',
    )
  })
})

/**
 * The windows other than the main one that wear the main bar on Windows and Linux (Tauri hands the
 * app-wide menu to every window built without one: `src-tauri/src/menu/DETAILS.md` § "A modal
 * surface"), by the scope their own commands live in. A bar accelerator fires before the page, so a
 * row registering one of their keys would take it from them.
 */
const BAR_WEARING_WINDOW_SCOPES: readonly CommandScope[] = ['Operation queue window', 'About window']

/**
 * The keys the menu bar must leave to the page, per platform, written where `cmdr-menu` reads them
 * (`include_str!` in `bar.rs`): `rebound_row_key` keeps a pushed combo on this list display-only
 * unless it IS the row's built key, and `bar_parity_test.rs` holds every built accelerator to it.
 * Two reasons: the platform's native text keys (`routes/(main)/native-text-keys.ts`), which a bar
 * accelerator would take from every focused text field, and, on Windows and Linux, the keys of the
 * windows in `BAR_WEARING_WINDOW_SCOPES`.
 */
describe('the keys the menu bar leaves to the page', () => {
  it('match crates/cmdr-menu/src/page_owned_keys.tsv', async () => {
    const lines = [
      '# platform\tcombo\twhy the bar leaves it to the page. Generated by `apps/desktop/src/lib/commands/default-keymap.test.ts`; update with `vitest -u`, ❌ never by hand.',
    ]
    for (const platform of PLATFORMS) {
      const owned = new Map<string, string>()
      const table = nativeTextKeys(platform)
      for (const combo of [...table.copyWithSelection, ...table.fieldOwned, ...table.bailInField]) {
        owned.set(combo, 'text field')
      }
      if (platform !== 'macos') {
        const undoPlatform = withPlatform(platform)
        const undoCapabilities = withCapabilitiesPossibleOn(platform)
        try {
          for (const command of commands.filter(commandOffered)) {
            if (!BAR_WEARING_WINDOW_SCOPES.includes(command.scope)) continue
            for (const combo of getDefaultShortcuts(command.id)) {
              if (!owned.has(combo)) owned.set(combo, command.scope)
            }
          }
        } finally {
          undoCapabilities()
          undoPlatform()
        }
      }
      for (const [combo, why] of owned) lines.push(`${platform}\t${combo}\t${why}`)
    }
    await expect(`${lines.join('\n')}\n`).toMatchFileSnapshot('../../../../../crates/cmdr-menu/src/page_owned_keys.tsv')
  })
})
