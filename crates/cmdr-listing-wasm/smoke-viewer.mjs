// The viewer half of the smoke run (`smoke.mjs` calls it): drives every viewer command the
// demo answers against the real `.wasm`, where a job runs inline and the bridge polls once,
// so a trap only the browser build has (a thread spawn, a `std` clock, a `Path` that's
// never absolute) fails a check instead of a visitor's viewer window.

const text = new TextEncoder()
const NOTES = 'first line\nsecond line has a needle\nthird line\n'
const README =
  '# Hello\n\nSee [the notes](../docs/notes.txt), ![a dot](dot.png), and [the site](https://getcmdr.com).\n'
// A one-pixel PNG's signature and header: enough to classify as an image.
const PNG = Uint8Array.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 0x0d, 0x49, 0x48, 0x44, 0x52, 0, 0, 0, 1, 0, 0, 0, 1, 8, 6,
  0, 0, 0, 0x1f, 0x15, 0xc4, 0x89,
])
const PDF = text.encode('%PDF-1.7\n1 0 obj\n<<>>\nendobj\n')
// The search budget's file: generated bytes, the size of the demo's largest text-like file.
const BIG_BYTES = 1024 * 1024
const SEARCH_BUDGET_MS = 200

/** Drives the viewer through `glue`'s `DemoListing`; calls `fail(message)` on the first miss. */
export async function smokeViewer(glue, fail) {
  const heard = []
  const demo = new glue.DemoListing(
    {
      volumeId: 'root',
      root: '/',
      entries: [
        { path: '/docs', kind: 'dir' },
        { path: '/docs/notes.txt', kind: 'file' },
        { path: '/docs/README.md', kind: 'file' },
        { path: '/docs/dot.png', kind: 'file' },
        { path: '/docs/paper.pdf', kind: 'file' },
        { path: '/docs/big.log', kind: 'file', size: BIG_BYTES },
      ],
    },
    (name, payload, target) => heard.push({ name, payload, target }),
    {
      '/docs/notes.txt': text.encode(NOTES),
      '/docs/README.md': text.encode(README),
      '/docs/dot.png': PNG,
      '/docs/paper.pdf': PDF,
    },
  )
  const call = (command, args) => demo.invoke(command, args)
  const open = (path, windowLabel) => call('viewer_open', { path, volumeId: 'root', windowLabel, rows: 'raw' })
  const mode = { useRegex: false, caseSensitive: false }

  // Text: rows, an inline search the first poll answers, an encoding switch, hex bytes.
  const notes = await open('/docs/notes.txt', 'viewer-text')
  if (notes.kind !== 'text' || notes.totalBytes !== NOTES.length) fail(`notes opened as ${JSON.stringify(notes)}`)
  const id = notes.sessionId
  const lines = await call('viewer_get_lines', { sessionId: id, targetType: 'row', targetValue: 1, count: 2 })
  if (lines.rows[0]?.text !== 'second line has a needle') fail(`rows came back as ${JSON.stringify(lines)}`)
  await call('viewer_search_start', { sessionId: id, query: 'needle', mode })
  const found = await call('viewer_search_poll', { sessionId: id, sinceIndex: 0 })
  if (found.status.status !== 'done' || found.newMatches[0]?.row !== 1) fail(`search polled ${JSON.stringify(found)}`)
  await call('viewer_set_encoding', { sessionId: id, encoding: 'windows1252' })
  const status = await call('viewer_get_status', { sessionId: id })
  if (status.isIndexing) fail(`the browser started an index: ${JSON.stringify(status)}`)
  const bytes = await call('viewer_get_bytes', { sessionId: id, offset: 0, count: 5 })
  if (String.fromCharCode(...bytes) !== 'first') fail(`hex bytes came back as ${JSON.stringify(bytes)}`)
  await call('viewer_close', { sessionId: id })

  // Markdown: a render, a relative link (a `..` the browser's `Path` must resolve as the
  // desktop's does), its local picture through its token, and a web link to the opener.
  const readme = await open('/docs/README.md', 'viewer-md')
  if (readme.kind !== 'markdown') fail(`README opened as ${readme.kind}`)
  const { html } = await call('viewer_render_markdown', { sessionId: readme.sessionId })
  const imageToken = /data-md-image="local:([0-9a-f]{32})"/.exec(html)?.[1]
  if (!imageToken) fail(`no picture token in ${html}`)
  const picture = demo.mediaBody(imageToken, 'viewer-md')
  if (picture?.mime !== 'image/png' || picture.bytes.length !== PNG.length) fail('the picture served wrong')
  const link = await call('viewer_follow_markdown_link', { sessionId: readme.sessionId, href: '../docs/notes.txt' })
  if (link.kind !== 'file' || link.path !== '/docs/notes.txt') fail(`the relative link went to ${JSON.stringify(link)}`)
  await call('viewer_follow_markdown_link', { sessionId: readme.sessionId, href: 'https://getcmdr.com' })
  if (!heard.some((e) => e.name === 'demo://open-url' && e.payload.url === 'https://getcmdr.com/')) {
    fail('the web link never reached the opener')
  }

  // Media: bodies served, and `viewer-media-load` Done told to the asking window only.
  const tokens = []
  for (const [path, kind, body, windowLabel] of [
    ['/docs/dot.png', 'image', PNG, 'viewer-img'],
    ['/docs/paper.pdf', 'pdf', PDF, 'viewer-pdf'],
  ]) {
    const media = await open(path, windowLabel)
    if (media.kind !== kind || media.mediaFromVolume !== true) fail(`${path} opened as ${JSON.stringify(media)}`)
    tokens.push(media.mediaToken)
    if (demo.mediaBody(media.mediaToken, windowLabel)?.bytes.length !== body.length) fail(`${path} served wrong`)
    const done = heard.findLast((e) => e.name === 'viewer-media-load')
    if (done?.target !== windowLabel || done.payload.stage !== 'done' || done.payload.token !== media.mediaToken) {
      fail(`${path}'s load was told as ${JSON.stringify(done)}`)
    }
  }
  if (tokens[0] === tokens[1] || !/^[0-9a-f]{32}$/.test(tokens[0])) fail(`tokens minted as ${tokens.join(', ')}`)

  // Closing a window frees its sessions, and each token's drop reaches the page.
  const dropsBefore = heard.filter((e) => e.name === 'demo://media-token-dropped').length
  demo.closeViewerWindow('viewer-img')
  const drops = heard.filter((e) => e.name === 'demo://media-token-dropped').slice(dropsBefore)
  if (drops.length !== 1 || drops[0].payload.token !== tokens[0]) fail(`closing dropped ${JSON.stringify(drops)}`)
  if (demo.mediaBody(tokens[0], 'viewer-img') !== undefined) fail('a dropped token still served')

  // A folder answers its own typed error, never the `notFound` a missing local file gives.
  try {
    await open('/docs', 'viewer-dir')
    fail('a folder opened')
  } catch (error) {
    if (error?.kind === undefined || error.kind === 'notFound') fail(`a folder rejected with ${JSON.stringify(error)}`)
  }

  // The biggest demo file searches inline, to the end, inside its budget.
  const big = await open('/docs/big.log', 'viewer-big')
  const started = performance.now()
  await call('viewer_search_start', { sessionId: big.sessionId, query: 'no such text anywhere', mode })
  const searched = await call('viewer_search_poll', { sessionId: big.sessionId, sinceIndex: 0 })
  const searchMs = Math.round(performance.now() - started)
  if (searched.status.status !== 'done') fail(`the big search polled ${JSON.stringify(searched)}`)
  if (searchMs > SEARCH_BUDGET_MS) fail(`searching ${BIG_BYTES} bytes took ${searchMs} ms`)
  demo.closeViewerWindow('viewer-big')

  return `viewer OK (a ${BIG_BYTES / 1024} KiB search in ${searchMs} ms)`
}
